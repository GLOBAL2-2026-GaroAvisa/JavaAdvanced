-- O card de mudanca passa a mostrar O QUE disparou a mudanca (feature 21).
-- Cada motivo preenche o seu proprio conjunto de campos:
--   CEU e TEMPERATURA -> ds_anterior / ds_atualizada ("30° e sol")
--   CHUVA             -> os mesmos campos, com a porcentagem no texto
--   ALERTA            -> tp_alerta e gravidade_alerta, sem antes e depois
-- Recriada em vez de alterada: as linhas se refazem no proximo ciclo
-- e expiram sozinhas quando o dia passa.
DROP TABLE T_GA_MUDANCA_PREVISAO CASCADE CONSTRAINTS;

CREATE TABLE T_GA_MUDANCA_PREVISAO (
    id_mudanca         NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    fk_id_endereco     NUMBER(10)    NOT NULL,
    dt_dia             DATE          NOT NULL,
    tp_motivo          VARCHAR2(15)  NOT NULL,
    ds_anterior        VARCHAR2(60 CHAR),
    categoria_anterior VARCHAR2(25),
    ds_atualizada      VARCHAR2(60 CHAR),
    categoria_atual    VARCHAR2(25),
    tp_alerta          VARCHAR2(15),
    gravidade_alerta   VARCHAR2(10),
    dt_registro        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT Mudanca_PK          PRIMARY KEY (id_mudanca),
    CONSTRAINT Mudanca_Endereco_FK FOREIGN KEY (fk_id_endereco)
        REFERENCES T_GA_ENDERECO (id_endereco) ON DELETE CASCADE,
    CONSTRAINT Mudanca_Dia_UK      UNIQUE (fk_id_endereco, dt_dia),
    CONSTRAINT Mudanca_Dia_CK      CHECK (dt_dia = TRUNC(dt_dia)),
    CONSTRAINT Mudanca_Motivo_CK   CHECK (tp_motivo IN ('CEU','TEMPERATURA','CHUVA','ALERTA'))
);