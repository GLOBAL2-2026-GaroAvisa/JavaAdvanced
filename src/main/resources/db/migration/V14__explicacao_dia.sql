-- Feature 23: o texto da Explicacao do Dia, gerado por IA e reaproveitado.
-- A chave muda conforme a tela:
--   Home     u:<usuario>|l:<local>|d:<dia>
--   Pesquisa c:<lat>,<lon>|d:<dia>   (coordenada arredondada, ~1 km)
-- So guarda o que veio da IA: o texto padrao e montado em memoria, para uma
-- falha momentanea nao congelar o texto ruim pelo resto do dia.
CREATE TABLE T_GA_EXPLICACAO_DIA (
    id_explicacao  NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    ds_chave       VARCHAR2(120) NOT NULL,
    fk_id_usuario  NUMBER(10),
    dt_dia         DATE          NOT NULL,
    ds_texto       VARCHAR2(1000 CHAR) NOT NULL,
    dt_criacao     TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT Explicacao_PK         PRIMARY KEY (id_explicacao),
    CONSTRAINT Explicacao_Chave_UK   UNIQUE (ds_chave),
    CONSTRAINT Explicacao_Usuario_FK FOREIGN KEY (fk_id_usuario)
        REFERENCES T_GA_USUARIO (id_usuario) ON DELETE CASCADE,
    CONSTRAINT Explicacao_Dia_CK     CHECK (dt_dia = TRUNC(dt_dia))
);