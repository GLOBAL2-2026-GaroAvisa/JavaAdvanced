-- A mudanca brusca passa a pertencer ao ENDERECO, nao ao Local.
-- A previsao e comparada uma vez por endereco e a mudanca vale para todos
-- os locais que usam aquele endereco (feature 21).
-- A tabela e recriada em vez de alterada: as mudancas sao refeitas na proxima
-- passada do relogio (no maximo uma hora) e expiram sozinhas quando o dia passa.
DROP TABLE T_GA_MUDANCA_PREVISAO CASCADE CONSTRAINTS;

CREATE TABLE T_GA_MUDANCA_PREVISAO (
    id_mudanca         NUMBER(10)    GENERATED BY DEFAULT AS IDENTITY,
    fk_id_endereco     NUMBER(10)    NOT NULL,
    dt_dia             DATE          NOT NULL,
    ds_anterior        VARCHAR2(60 CHAR) NOT NULL,
    categoria_anterior VARCHAR2(25)  NOT NULL,
    ds_atualizada      VARCHAR2(60 CHAR) NOT NULL,
    categoria_atual    VARCHAR2(25)  NOT NULL,
    dt_registro        TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT Mudanca_PK          PRIMARY KEY (id_mudanca),
    CONSTRAINT Mudanca_Endereco_FK FOREIGN KEY (fk_id_endereco)
        REFERENCES T_GA_ENDERECO (id_endereco) ON DELETE CASCADE,
    CONSTRAINT Mudanca_Dia_UK      UNIQUE (fk_id_endereco, dt_dia),
    CONSTRAINT Mudanca_Dia_CK      CHECK (dt_dia = TRUNC(dt_dia))
);