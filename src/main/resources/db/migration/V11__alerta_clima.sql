-- Feature 80: os alertas de clima de um endereco, para cada um dos 16 dias.
-- Calculados uma vez por endereco e compartilhados por todos os locais que
-- o usam, igual as mudancas bruscas.
CREATE TABLE T_GA_ALERTA_CLIMA (
    id_alerta      NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    fk_id_endereco NUMBER(10)   NOT NULL,
    tp_alerta      VARCHAR2(15) NOT NULL,
    dt_dia         DATE         NOT NULL,
    gravidade      VARCHAR2(10) NOT NULL,
    vl_atingido    NUMBER(6,2),
    hr_primeira    NUMBER(2),
    st_ativo       NUMBER(1)    DEFAULT 1 NOT NULL,
    dt_atualizacao TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT Alerta_PK          PRIMARY KEY (id_alerta),
    CONSTRAINT Alerta_Endereco_FK FOREIGN KEY (fk_id_endereco)
        REFERENCES T_GA_ENDERECO (id_endereco) ON DELETE CASCADE,
    CONSTRAINT Alerta_UK          UNIQUE (fk_id_endereco, tp_alerta, dt_dia),
    CONSTRAINT Alerta_Dia_CK      CHECK (dt_dia = TRUNC(dt_dia)),
    CONSTRAINT Alerta_Tipo_CK     CHECK (tp_alerta IN
        ('CHUVA','TEMPESTADE','CALOR','FRIO','RAJADA','UV')),
    CONSTRAINT Alerta_Grav_CK     CHECK (gravidade IN ('MEDIA','ALTA')),
    CONSTRAINT Alerta_Ativo_CK    CHECK (st_ativo IN (0,1)),
    CONSTRAINT Alerta_Hora_CK     CHECK (hr_primeira BETWEEN 0 AND 23)
);