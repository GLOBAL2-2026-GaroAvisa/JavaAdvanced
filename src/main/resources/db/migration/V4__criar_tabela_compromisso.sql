CREATE TABLE T_GA_COMPROMISSO (
    id_compromisso  NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    nm_compromisso  VARCHAR2(80) NOT NULL,
    dt_compromisso  DATE         NOT NULL,
    fk_id_local     NUMBER(10)   NOT NULL,
    CONSTRAINT Compromisso_PK       PRIMARY KEY (id_compromisso),
    CONSTRAINT Compromisso_Local_FK FOREIGN KEY (fk_id_local)
        REFERENCES T_GA_LOCAL (id_local) ON DELETE CASCADE,
    -- Só a data: a hora precisa ser 00:00:00
    CONSTRAINT Compromisso_Data_CK  CHECK (dt_compromisso = TRUNC(dt_compromisso))
);

-- O Oracle não cria índice em FK automaticamente
CREATE INDEX Compromisso_Local_IX ON T_GA_COMPROMISSO (fk_id_local, dt_compromisso);