CREATE TABLE T_GA_ENDERECO (
    id_endereco  NUMBER(10)   GENERATED BY DEFAULT AS IDENTITY,
    pais         VARCHAR2(50) NOT NULL,
    estado       VARCHAR2(50) NOT NULL,
    cidade       VARCHAR2(60) NOT NULL,
    bairro       VARCHAR2(60) NOT NULL,
    latitude     NUMBER(9,6)  NOT NULL,
    longitude    NUMBER(9,6)  NOT NULL,
    fuso         VARCHAR2(50) NOT NULL,
    CONSTRAINT Endereco_PK             PRIMARY KEY (id_endereco),
    CONSTRAINT Endereco_Coordenadas_UK UNIQUE (latitude, longitude)
);